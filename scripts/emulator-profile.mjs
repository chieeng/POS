/**
 * Builds the config that `npm run emulators` uses for LOCAL DEVELOPMENT ONLY.
 *
 * The Auth emulator cannot do authenticator-app (TOTP) codes, so a local Owner can never
 * satisfy the second-factor check (SEC-05) and could not open any Owner screen. This writes
 * a copy of firestore.rules with that one check relaxed, plus a firebase config that points
 * the emulators at the copy. Both outputs are git-ignored.
 *
 * Nothing here can reach a real project: `firebase deploy`, CI and `npm run test:emulators`
 * all use firebase.json and the real firestore.rules.
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';

const REAL_CHECK = "return claims().firebase.get('sign_in_second_factor', '') == 'totp';";
const RELAXED_CHECK = 'return true; // LOCAL EMULATOR ONLY: the Auth emulator has no TOTP.';

const rules = readFileSync('firestore.rules', 'utf8');
if (rules.split(REAL_CHECK).length !== 2) {
  console.error(
    'emulator-profile: expected exactly one second-factor check in firestore.rules.\n' +
      'Update REAL_CHECK in scripts/emulator-profile.mjs to match the rules.',
  );
  process.exit(1);
}

mkdirSync('.emulator', { recursive: true });
writeFileSync(
  '.emulator/firestore.rules',
  '// GENERATED by scripts/emulator-profile.mjs for the local emulator. Do not edit or deploy.\n' +
    rules.replace(REAL_CHECK, RELAXED_CHECK),
);

const config = JSON.parse(readFileSync('firebase.json', 'utf8'));
config.firestore.rules = '.emulator/firestore.rules';
writeFileSync('firebase.emulator.json', JSON.stringify(config, null, 2) + '\n');
